"""`tkt init` — scaffold a project: write .sdlc/config.toml from an example,
optionally link the skill pack into .claude/, and print next steps.

Runs BEFORE config exists, so it never calls Config.load().
"""
import contextlib
import os
import re
import stat
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path, PurePath
from urllib.parse import urlsplit

from . import config as config_mod
from . import tomledit, toolchain
from .schema import Check
from .errors import ConfigError, NotFoundError, UsageError

PACK_ROOT = Path(__file__).resolve().parent.parent


def available_providers() -> list[str]:
    ex = PACK_ROOT / "examples"
    return sorted(p.name[len("config."):-len(".toml")]
                  for p in ex.glob("config.*.toml"))


_STARTER_TICKET = """\
---
type: Story
status: To Do
priority: Highest
assignee: {me}
blocked_by: []
blocks: []
---
# First ticket — replace me

Created by `tkt init --sample`. Edit or delete this file.

## Acceptance
- the board lists this ticket
"""


_KEY_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
_REPO_PLACEHOLDERS = {"your-org/your-repo", "owner/repo"}
# provider -> (table, key, validated as a <KEY>-N prefix) that --project sets
_PROJECT_KEY = {"markdown": ("ticketing", "project", True),
                "jira": ("ticketing", "project", True),
                "linear": ("linear", "team_key", True),
                "openkanban": ("openkanban", "project", False)}


def _tbl(data: dict, name: str) -> dict:
    t = data.get(name, {})
    return t if isinstance(t, dict) else {}


def derive_key(name: str) -> str:
    """Ticket key from a repo dir name: `tkt` -> TKT, long multi-word names
    -> initials (`ai-map-reference-platform` -> AMRP)."""
    words = re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|[0-9]+", name)
    key = "".join(words).upper()
    if len(key) > 10:
        key = "".join(w[0] for w in words).upper() if len(words) > 1 else key[:10]
    return key.lstrip("0123456789") or "PROJ"


def _validate_key(key: str) -> str:
    if not _KEY_RE.match(key):
        raise UsageError(f"invalid project key {key!r}: use letters, digits and _ "
                         "only, starting with a letter (keys read <KEY>-N)")
    return key


def _find_parent_config(target: Path, stop: Path | None = None):
    """Nearest ancestor .sdlc/config.toml, as (path, data), when it is a
    markdown board a child can join. Ignores $TKT_CONFIG."""
    for d in target.parents:
        cand = d / ".sdlc" / "config.toml"
        try:
            found = cand.is_file()
        except OSError:
            found = False
        if found:
            try:
                data = tomllib.loads(cand.read_text())
            except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as e:
                print(f"warning: not inheriting from {cand}: {e}", file=sys.stderr)
                return None
            t, md = data.get("ticketing"), data.get("markdown", {})
            if not (isinstance(t, dict) and t.get("provider") == "markdown"
                    and isinstance(md, dict)):
                return None
            return cand, data
        if stop is not None and d == stop:
            break
    return None


def _resolve(base: Path, raw: str) -> Path:
    """Same rule as MarkdownAdapter._resolve, normalized for comparison."""
    p = Path(raw).expanduser()
    return Path(os.path.normpath(p if p.is_absolute() else base / p))


def _rebase(raw: str, parent_root: Path, child_root: Path) -> str | None:
    """Parent path value as the child should write it; None = copy verbatim."""
    if Path(raw).expanduser().is_absolute():
        return None
    try:
        return os.path.relpath(_resolve(parent_root, raw), child_root)
    except ValueError:              # different drive on Windows
        return str(_resolve(parent_root, raw))


def _ask(prompt: str, default: str) -> str:
    try:
        return input(prompt).strip() or default
    except EOFError:
        return default


def _render_inherited(parent: Path, pdata: dict, example: str,
                      child_root: Path) -> str:
    """Parent config text with a repo-specific [vcs]/[build] and the parent's
    relative markdown paths rebased onto the child."""
    lines = parent.read_text().splitlines(keepends=True)
    while lines and (not lines[0].strip() or lines[0].lstrip().startswith("#")):
        lines.pop(0)
    text = (f"# Generated by `tkt init` from {parent}:\n"
            "# shared markdown board; [ticketing].project, [vcs] and [build] "
            "are this repo's.\n\n" + "".join(lines))
    proot = config_mod.project_root(parent)
    md = _tbl(pdata, "markdown")
    paths = {}
    for k, default in (("board_dir", ".sdlc/board"), ("state_dir", ".sdlc/state")):
        new = _rebase(str(md.get(k, default)), proot, child_root)
        if new is not None:
            paths[k] = new
    text = tomledit.set_keys(text, "markdown", paths)
    run = pdata.get("run")
    run_state = run.get("state_dir") if isinstance(run, dict) else None
    if isinstance(run_state, str) and run_state:
        new = _rebase(run_state, proot, child_root)
        if new is not None:
            text = tomledit.set_keys(text, "run", {"state_dir": new})
    for t in ("vcs", "build"):
        text = tomledit.replace_table(text, t, tomledit.table_block(example, t))
    return tomledit.replace_table(text, "deploy", None)


def init(provider: str | None, target_dir: str, force: bool,
         link_skills: bool, sample: bool, interactive: bool,
         detect_build: bool = True, project: str | None = None,
         board_dir: str | None = None, inherit: bool = True,
         stop: Path | None = None, detect_repo: bool = True) -> int:
    providers = available_providers()
    tty = interactive and sys.stdin.isatty()

    if not provider:
        if tty:
            print("Pick a ticketing backend:")
            for i, p in enumerate(providers, 1):
                print(f"  {i}) {p}")
            choice = input("> ").strip()
            provider = (providers[int(choice) - 1] if choice.isdigit()
                        and 1 <= int(choice) <= len(providers) else choice)
        else:
            raise UsageError(
                "init needs --provider <name> (or run interactively). "
                f"Available: {', '.join(providers)}")
    if provider not in providers:
        raise ConfigError(f"no example config for provider '{provider}'. "
                          f"Available: {', '.join(providers)}")
    markdown = provider == "markdown"
    if board_dir is not None and not markdown:
        raise UsageError("--board-dir only applies to --provider markdown")

    target = Path(target_dir).expanduser().resolve()
    sdlc = target / ".sdlc"
    cfg = sdlc / "config.toml"
    src = PACK_ROOT / "examples" / f"config.{provider}.toml"

    if cfg.exists() and not force:
        raise ConfigError(f"{cfg} already exists (use --force to overwrite)")

    if project is not None:
        if provider not in _PROJECT_KEY:
            hint = "; set [github].repo" if provider == "github" else ""
            raise UsageError(f"--project does not apply to {provider}{hint}")
        if _PROJECT_KEY[provider][2]:
            _validate_key(project)
        elif not project.strip():
            raise UsageError("--project needs a non-empty value")
    elif markdown:
        project = derive_key(target.name)
        if tty:
            project = _validate_key(_ask(f"Project key [{project}]: ", project))

    parent = _find_parent_config(target, stop) if markdown and inherit else None
    shared_board = shared_state = None
    if parent:
        pcfg, pdata = parent
        proot, pmd = config_mod.project_root(pcfg), _tbl(pdata, "markdown")
        shared_board = _resolve(proot, str(pmd.get("board_dir", ".sdlc/board")))
        shared_state = _resolve(proot, str(pmd.get("state_dir", ".sdlc/state")))
        if board_dir is not None:
            print(f"inheriting {pcfg} (board: {board_dir}); --no-inherit to skip")
        elif tty:
            ans = _ask(f"Join shared board {shared_board} (from {pcfg})? [Y/n] ", "y")
            if ans.lower().startswith("n"):
                parent = None
        else:
            print(f"inheriting {pcfg}: joining shared board {shared_board}; "
                  "--no-inherit for a private board")

    example = src.read_text()
    text = _render_inherited(pcfg, pdata, example, target) if parent else example
    if project is not None:
        table, key, _ = _PROJECT_KEY[provider]
        text = tomledit.set_keys(text, table, {key: project},
                                 keep_comment=not parent)
    state_dir = None
    if board_dir is not None:
        state_dir = str(PurePath(board_dir).parent / "state")
        text = tomledit.set_keys(text, "markdown", {"board_dir": board_dir,
                                                    "state_dir": state_dir})
    build_notes = []
    if detect_build:
        text, build_notes = _seed_build(text, target)
    repo_notes, repo = [], None
    if detect_repo:
        text, repo_notes, repo = _seed_repo(text, target)

    # Re-parse what we built; a mismatch means the text surgery went wrong.
    retry = "; re-run with --no-inherit" if parent else ""
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise ConfigError(f"generated config is not valid TOML ({e}); "
                          f"{cfg} left untouched{retry}") from e
    got = want = None
    if project is not None:
        table, key, _ = _PROJECT_KEY[provider]
        got, want = [_tbl(data, table).get(key)], [project]
    board = None
    if markdown:
        md = _tbl(data, "markdown")
        board = _resolve(target, str(md.get("board_dir", ".sdlc/board")))
        state = _resolve(target, str(md.get("state_dir", ".sdlc/state")))
        if board_dir is not None:
            exp = (_resolve(target, board_dir), _resolve(target, state_dir))
        elif parent:
            exp = (shared_board, shared_state)
        else:
            exp = (_resolve(target, ".sdlc/board"), _resolve(target, ".sdlc/state"))
        got, want = got + [board, state], want + list(exp)
    if repo is not None:
        got = (got or []) + [_tbl(data, "vcs").get("repo")]
        want = (want or []) + [repo]
    if got != want:
        raise ConfigError(f"generated config resolves to {got}, expected {want}; "
                          f"{cfg} left untouched{retry}")

    shared = board is not None and not Path(os.path.realpath(board)).is_relative_to(target)
    if shared and not _same_project(cfg, target, project, board):
        pat = re.compile(rf"^{re.escape(project)}-\d+\.md$", re.IGNORECASE)
        try:
            n = sum(1 for f in os.listdir(board) if pat.match(f))
        except OSError:
            n = 0
        if n:
            print(f"warning: {n} ticket(s) keyed {project} already on {board}; "
                  "another repo may own this key (use --project)", file=sys.stderr)

    sdlc.mkdir(parents=True, exist_ok=True)
    _write_atomic(cfg, text)
    origin = f"inherits {pcfg}" if parent else f"from examples/config.{provider}.toml"
    print(f"wrote {cfg}  ({origin})")
    for line in build_notes + repo_notes:
        print(line)

    if sample and markdown:
        if shared:
            print(f"  skipped --sample: {board} is a shared board")
        else:
            board.mkdir(parents=True, exist_ok=True)
            starter = board / f"{project}-1.md"
            if not starter.exists() or force:
                starter.write_text(_STARTER_TICKET.format(me=os.environ.get("USER", "me")))
                print(f"wrote {starter}  (starter ticket; --sample)")

    if link_skills:
        _link_pack(target)

    print()
    print("Next steps:")
    print(f"  1. Edit {cfg}")
    if provider == "jira":
        print("  2. Export CONFLUENCE_SITE / CONFLUENCE_EMAIL / CONFLUENCE_API_TOKEN")
    elif provider == "linear":
        print("  2. Export LINEAR_API_KEY")
    elif provider == "github":
        print("  2. gh auth login (and `-s project,read:project` for projectv2 boards)")
    else:
        print("  2. (markdown: no auth needed)")
    print(f"  3. {_tkt_invocation()} doctor")
    if not link_skills:
        print("  4. Activate skills: `tkt sync-pack` (committed copies — best for "
              "cloud/CI harnesses like Copilot) or `tkt init --link-skills` (symlinks)")
        print("     add a harness later with `tkt sync-pack cursor` "
              "(`--list-harnesses` for the names)")
    return 0


def _same_project(cfg: Path, target: Path, project: str, board: Path) -> bool:
    """True when the config being replaced (--force) already had this key on
    this board, so its tickets are this repo's own."""
    try:
        old = tomllib.loads(cfg.read_text())
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError):
        return False
    old_board = _resolve(target, str(_tbl(old, "markdown").get("board_dir", ".sdlc/board")))
    return (_tbl(old, "ticketing").get("project") == project
            and os.path.realpath(old_board) == os.path.realpath(board))


def _write_atomic(path: Path, text: str) -> None:
    try:                            # keep an existing file's mode (--force)
        mode = stat.S_IMODE(path.stat().st_mode)
    except FileNotFoundError:       # else what a plain create would get, not 0600
        umask = os.umask(0)
        os.umask(umask)
        mode = 0o666 & ~umask
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".config.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w") as fh:
            os.fchmod(fh.fileno(), mode)
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise


def _seed_build(text: str, target: Path) -> tuple[str, list[str]]:
    """Replace the example's placeholder [build] commands with detected ones.
    Returns the new text and the lines to report."""
    found, label = toolchain.detect(target)
    if not found:
        return text, ["  no build/test commands detected — [build] left at example "
                      "defaults (edit by hand)"]
    notes = [f"  detected {label} toolchain; [build] set to:"]
    notes += [f"    {k:<9} = {found[k]}" for k in toolchain.KEYS if k in found]
    missing = [k for k in toolchain.KEYS if k not in found]
    if missing:
        notes.append(f"  not declared by the project (left as-is): {', '.join(missing)}")
    return toolchain.apply_to_config(text, found), notes


_OWNER_RE = re.compile(r"^[A-Za-z0-9_.][A-Za-z0-9_.-]*$")
_REPO_RE = re.compile(r"^[A-Za-z0-9_.-]+$")
# scp-like `[user@]host:path`; git reads it as a URL only when no `/`
# comes before the first `:`
_SCP_RE = re.compile(r"^(?:(?P<user>[^@/\s]+)@)?(?P<host>[^@:/\s]+):(?P<path>\S*)$")
_URL_SCHEMES = {"https", "http", "ssh", "git", "git+ssh", "ssh+git"}
# well-known hosts that are not GitHub (subdomains included); an unknown
# host is taken as GitHub, since it may be a ~/.ssh/config alias
_NON_GITHUB_HOSTS = ("gitlab.com", "bitbucket.org", "codeberg.org",
                     "dev.azure.com", "ssh.dev.azure.com", "visualstudio.com")
# variables a git hook exports that would point `git -C <target>` elsewhere
_GIT_LOCATION_ENV = ("GIT_DIR", "GIT_WORK_TREE", "GIT_COMMON_DIR")


def _split_remote(url: str) -> tuple[str, str] | None:
    """(host, owner/repo) from an scp-like SSH, `ssh://`, `git://` or
    HTTP(S) remote URL; None for anything else, including local paths and
    paths that are not exactly two segments. The host never carries
    credentials."""
    url = url.strip()
    if "://" in url:
        try:
            parts = urlsplit(url)
            host = parts.hostname
        except ValueError:          # e.g. an unclosed `[` IPv6 host
            return None
        if parts.scheme.lower() not in _URL_SCHEMES or not host:
            return None
        path = parts.path
    else:
        m = _SCP_RE.match(url)
        # a one-letter host with no user is a Windows drive (`C:/src/x`)
        if not m or (len(m.group("host")) == 1 and not m.group("user")):
            return None
        host, path = m.group("host"), m.group("path")
    path = path.strip("/")
    if path.lower().endswith(".git"):
        path = path[:-len(".git")]
    segs = path.split("/")
    if len(segs) != 2 or not (_OWNER_RE.match(segs[0]) and _REPO_RE.match(segs[1])) \
            or any(s in (".", "..") for s in segs):
        return None
    return host.lower(), path


def _github_host(host: str) -> bool:
    return not any(host == h or host.endswith("." + h) for h in _NON_GITHUB_HOSTS)


def parse_remote(url: str) -> str | None:
    """`owner/repo` from a GitHub remote URL: scp-like SSH (any host, so
    `~/.ssh/config` aliases such as `git@github-work:o/r.git` work),
    `ssh://`, `git://` or HTTP(S). None for anything else, including a
    well-known non-GitHub host."""
    split = _split_remote(url)
    return split[1] if split and _github_host(split[0]) else None


def _git(target: Path, *args: str) -> str | None:
    """stdout of `git -C target ARGS`, stripped; None when git is missing,
    fails or prints nothing."""
    env = {k: v for k, v in os.environ.items() if k not in _GIT_LOCATION_ENV}
    try:
        r = subprocess.run(["git", "-C", str(target), *args],
                           capture_output=True, encoding="utf-8",
                           errors="replace", timeout=10, env=env)
    except (OSError, subprocess.SubprocessError):
        return None
    return (r.stdout.strip() or None) if r.returncode == 0 else None


def _origin_url(target: Path) -> tuple[str | None, str]:
    """(origin URL, why not) for the repo rooted at `target`. The URL is
    None when git is missing, `target` is not the top of its own repo (an
    enclosing repo's origin is not this project's), or there is no origin;
    the reason then says which."""
    top = _git(target, "rev-parse", "--show-toplevel")
    if top is None:
        return None, "not a git repo"
    try:
        own = os.path.samefile(top, target)
    except OSError:
        own = False
    if not own:
        return None, "not the top of its own git repo"
    url = _git(target, "remote", "get-url", "origin")
    return url, "" if url else "no git origin remote"


def _seed_repo(text: str, target: Path) -> tuple[str, list[str], str | None]:
    """Fill a placeholder GitHub `[vcs].repo` from the origin remote.
    Returns the new text, the lines to report, and the repo written (None
    when nothing changed). Advisory: a missing or unrecognised remote
    leaves the text as it was."""
    try:
        vcs = _tbl(tomllib.loads(text), "vcs")
    except tomllib.TOMLDecodeError:
        return text, [], None       # the caller's re-parse reports it
    cur = vcs.get("repo")
    if vcs.get("provider") != "github" or not isinstance(cur, str) \
            or cur not in _REPO_PLACEHOLDERS:
        return text, [], None
    url, why = _origin_url(target)
    split = _split_remote(url) if url else None
    if url and split is None:
        # never echo the URL: an HTTPS remote can carry a token
        why = "git origin remote is not an owner/repo URL"
    elif split and not _github_host(split[0]):
        why = f"git origin remote is on {split[0]}, not GitHub"
    if why:
        return text, [f'  {why}; [vcs].repo left as "{cur}" (edit by hand)'], None
    repo = split[1]
    return (tomledit.set_keys(text, "vcs", {"repo": repo}),
            [f"  detected [vcs].repo = {repo} (from the git origin remote)"], repo)


def _link_pack(target: Path) -> None:
    claude = target / ".claude"
    for kind in ("skills", "agents"):
        srcdir = PACK_ROOT / kind
        if not srcdir.exists():
            continue
        dstdir = claude / kind
        dstdir.mkdir(parents=True, exist_ok=True)
        for item in sorted(srcdir.iterdir()):
            link = dstdir / item.name
            if link.exists() or link.is_symlink():
                print(f"  skip (exists): {link}")
                continue
            link.symlink_to(item.resolve())
            print(f"  linked {link} -> {item.resolve()}")


def _tkt_invocation() -> str:
    exe = PACK_ROOT / "tkt"
    return str(exe) if exe.exists() else "tkt"


def doctor_check(config) -> Check | None:
    """Always-ok warning row when the config still carries an example
    placeholder project key or [vcs].repo; None when clean. Skipped inside a
    tkt checkout, whose own key is the markdown example's."""
    root = config.root
    if (root / "core" / "scaffold.py").is_file() and \
            (root / "examples" / "config.markdown.toml").is_file():
        return None
    try:
        ex = tomllib.loads((PACK_ROOT / "examples" /
                            f"config.{config.provider}.toml").read_text())
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError):
        ex = {}
    hits = []
    table, key, _ = _PROJECT_KEY.get(config.provider,
                                     ("ticketing", "project", True))
    ex_key = _tbl(ex, table).get(key)
    try:
        cur = config.get(f"{table}.{key}")
    except NotFoundError:
        cur = None
    if isinstance(ex_key, str) and ex_key and cur == ex_key:
        hits.append(f'[{table}].{key} = "{ex_key}"')
    repo = config.vcs.get("repo", "") if isinstance(config.vcs, dict) else ""
    if isinstance(repo, str) and repo and \
            repo in _REPO_PLACEHOLDERS | {_tbl(ex, "vcs").get("repo")}:
        hits.append(f'[vcs].repo = "{repo}"')
    if not hits:
        return None
    return Check("config placeholders", True,
                 f"warning: example placeholder {', '.join(hits)} in {config.path}")
